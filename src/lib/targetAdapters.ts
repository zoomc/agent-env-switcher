function formatConfigForDiff(
  targetType: TargetType,
  profile: Profile | TargetProfile,
): string {
  switch (targetType) {
    case 'claude-code':
      return formatClaudeCodeConfig(profile);
    case 'hermes':
      return formatHermesYaml(profile);
    case 'codex':
      return formatCodexToml(profile);
    case 'openclaw':
      return formatOpenClawConfig(profile);
    case 'openai-compatible-api':
      return JSON.stringify(
        {
          OPENAI_API_KEY: profile.apiKey,
          OPENAI_BASE_URL: profile.baseUrl,
          OPENAI_MODEL: profile.defaultModel,
        },
        null,
        2
      );
    default:
      return '';
  }
}

function createDiff(
  targetType: TargetType,
  beforeContent: string,
  afterContent: string
): DryRunChange | null {
  if (beforeContent.trim() === afterContent.trim()) return null;
  return {
    file: TARGET_CONFIG_PATHS[targetType] || 'Unknown',
    action: beforeContent.trim() ? 'modify' : 'create',
    before: beforeContent,
    after: afterContent,
  };
}

export const targetAdapter: TargetAdapter = {
  async read(targetType: TargetType): Promise<string> {
    const raw = await readRawConfig(targetType);
    return raw || '';
  },

  async write(targetType: TargetType, profile: Profile | TargetProfile): Promise<void> {
    if (targetType === 'openai-compatible-api') {
      throw new Error('OpenAI-compatible API config is env-var based; generate export instead');
    }

    const currentContent = await this.read(targetType);
    let content: string;

    switch (targetType) {
      case 'hermes': {
        let existing: Record<string, unknown> = {};
        if (currentContent.trim()) {
          existing = parseHermesYaml(currentContent);
        }
        content = mergeHermesYaml(existing, profile);
        break;
      }
      case 'codex': {
        let existing: Record<string, Record<string, string>> = {};
        if (currentContent.trim()) {
          existing = parseCodexToml(currentContent);
        }
        content = mergeCodexToml(existing, profile);
        break;
      }
      case 'claude-code': {
        let existing: Record<string, unknown> = {};
        if (currentContent.trim()) {
          try {
            existing = JSON.parse(currentContent);
          } catch {
            throw new Error(
              'Claude Code existing config is invalid JSON; cannot safely merge'
            );
          }
        }
        const merged = {
          ...existing,
          provider: profile.providerType,
          baseUrl: profile.baseUrl,
          apiKey: profile.apiKey,
          models: {
            ...(typeof existing.models === 'object' && existing.models !== null
              ? (existing.models as Record<string, unknown>)
              : {}),
            default: profile.defaultModel,
            fast: profile.fastModel,
            reasoning: profile.reasoningModel,
          },
        };
        content = JSON.stringify(merged, null, 2);
        break;
      }
      case 'openclaw': {
        let existing: Record<string, unknown> = {};
        if (currentContent.trim()) {
          try {
            existing = JSON.parse(currentContent);
          } catch {
            throw new Error(
              'OpenClaw existing config is invalid JSON; cannot safely merge'
            );
          }
        }
        const merged = {
          ...existing,
          provider: profile.providerType,
          baseUrl: profile.baseUrl,
          apiKey: profile.apiKey,
          model: profile.defaultModel,
          fastModel: profile.fastModel,
          reasoningModel: profile.reasoningModel,
        };
        content = JSON.stringify(merged, null, 2);
        break;
      }
      default:
        throw new Error(`Unsupported target type: ${targetType}`);
    }

    await writeRawConfig(targetType, content);

    if (targetType === 'claude-code') {
      const envContent = generateClaudeCodeEnvExport(profile);
      const home = await homeDir();
      const envPath = `${home}.claude/.env`;
      const dirPath = envPath.split('/').slice(0, -1).join('/');
      const dirExists = await exists(dirPath);
      if (!dirExists) {
        await mkdir(dirPath, { recursive: true });
      }
      await writeTextFile(envPath, envContent);
    }
  },

  async backup(
    targetType: TargetType,
    profileId: string,
    profileName: string
  ): Promise<BackupRecord | null> {
    const raw = await readRawConfig(targetType);
    if (!raw) return null;
    return await createBackupRecord(targetType, raw, profileId, profileName);
  },

  diff(
    targetType: TargetType,
    profile: Profile | TargetProfile,
    currentContent: string
  ): DryRunChange | null {
    const after = formatConfigForDiff(targetType, profile);
    return createDiff(targetType, currentContent, after);
  },
};

export function generateClaudeCodeEnvExportContent(profile: Profile | TargetProfile): string {
  return generateClaudeCodeEnvExport(profile);
}

export async function generateDryRun(profile: Profile): Promise<DryRunResult[]> {
  const results: DryRunResult[] = [];
  for (const targetType of profile.enabledTargets) {
    const target = knownTargets.find((t) => t.type === targetType);
    let status: DryRunResult['status'] = 'pending';
    let changes: DryRunChange[] = [];

    try {
      const currentContent = await targetAdapter.read(targetType);
      const change = targetAdapter.diff(targetType, profile, currentContent);
      if (change) {
        changes = [change];
        status = 'ready';
      }
    } catch (err) {
      status = 'failed';
      changes = [
        {
          file: TARGET_CONFIG_PATHS[targetType] || 'Unknown',
          action: 'modify',
          before: '',
          after: `Error: ${err instanceof Error ? err.message : String(err)}`,
        },
      ];
    }

    results.push({
      id: `dryrun-${profile.id}-${targetType}-${Date.now()}`,
      profileId: profile.id,
      profileName: profile.name,
      targetType,
      targetName: target?.name || targetType,
      timestamp: new Date().toISOString(),
      changes,
      status,
    });
  }
  return results;
}


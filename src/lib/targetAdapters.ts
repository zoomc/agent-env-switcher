import type {
  Profile,
  TargetType,
  TargetProfile,
  DryRunResult,
  DryRunChange,
  BackupRecord,
  HealthStatus,
} from '@/types';
import { RESTORE_SUPPORTED_TARGETS, TARGET_CONFIG_PATHS } from '@/types';
import { knownTargets } from '@/data/mock';
import { exists, mkdir, readTextFile, writeTextFile } from '@tauri-apps/plugin-fs';
import { appConfigDir, homeDir } from '@tauri-apps/api/path';

export interface TargetAdapter {
  read(targetType: TargetType): Promise<string>;
  write(targetType: TargetType, profile: Profile | TargetProfile): Promise<void>;
  backup(
    targetType: TargetType,
    profileId: string,
    profileName: string
  ): Promise<BackupRecord | null>;
  diff(
    targetType: TargetType,
    profile: Profile | TargetProfile,
    currentContent: string
  ): DryRunChange | null;
}

async function resolveHomePath(relativePath: string): Promise<string> {
  const home = await homeDir();
  const cleanPath = relativePath.replace(/^~/, '');
  return `${home}${cleanPath}`;
}

async function readRawConfig(targetType: TargetType): Promise<string | null> {
  const path = TARGET_CONFIG_PATHS[targetType];
  if (path === 'Environment variables') {
    return JSON.stringify({});
  }
  const fullPath = await resolveHomePath(path);
  try {
    return await readTextFile(fullPath);
  } catch {
    return null;
  }
}

async function writeRawConfig(targetType: TargetType, content: string): Promise<void> {
  const path = TARGET_CONFIG_PATHS[targetType];
  if (path === 'Environment variables') {
    throw new Error('Writing environment variables is not supported directly');
  }
  const fullPath = await resolveHomePath(path);
  const dirPath = fullPath.split('/').slice(0, -1).join('/');
  const dirExists = await exists(dirPath);
  if (!dirExists) {
    await mkdir(dirPath, { recursive: true });
  }
  await writeTextFile(fullPath, content);
}

async function computeChecksum(content: string): Promise<string> {
  const encoder = new TextEncoder();
  const data = encoder.encode(content);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
}

async function createBackupRecord(
  targetType: TargetType,
  originalContent: string,
  profileId: string,
  profileName: string
): Promise<BackupRecord> {
  const appConfig = await appConfigDir();
  const backupDir = `${appConfig}agent-env-switcher/backups`;
  const dirExists = await exists(backupDir);
  if (!dirExists) {
    await mkdir(backupDir, { recursive: true });
  }
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  const backupFileName = `${targetType}-${timestamp}.bak`;
  const backupPath = `${backupDir}/${backupFileName}`;
  await writeTextFile(backupPath, originalContent);

  const checksum = await computeChecksum(originalContent);
  const target = knownTargets.find((t) => t.type === targetType);

  return {
    id: `backup-${targetType}-${Date.now()}`,
    targetType,
    targetName: target?.name || targetType,
    profileId,
    profileName,
    createdAt: new Date().toISOString(),
    originalConfigPath: TARGET_CONFIG_PATHS[targetType] || 'Unknown',
    backupFilePath: backupPath,
    backupFileSize: new Blob([originalContent]).size,
    restoreSupported: (RESTORE_SUPPORTED_TARGETS as readonly string[]).includes(targetType),
    checksum,
  };
}

function formatHermesYaml(profile: Profile | TargetProfile): string {
  const provider = profile.providerType;
  const baseUrl = profile.baseUrl;
  const defaultModel = profile.defaultModel;
  const fastModel = profile.fastModel;
  const reasoningModel = profile.reasoningModel;
  const apiKey = profile.apiKey;

  return `# Generated by Agent Env Switcher
# DO NOT edit manually while using profile management

model:
  provider: ${provider}
  default: ${defaultModel}
  base_url: ${baseUrl}

providers:
  ${provider}:
    base_url: ${baseUrl}
    api_key: ${apiKey}

model_aliases:
  fast: ${fastModel}
  reasoning: ${reasoningModel}
`;
}

function parseHermesYaml(content: string): Record<string, unknown> {
  const result: Record<string, unknown> = {};
  const lines = content.split('\n');
  let currentSection = '';
  let currentSubSection = '';

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const sectionMatch = trimmed.match(/^(\w+):\s*$/);
    if (sectionMatch) {
      currentSection = sectionMatch[1];
      currentSubSection = '';
      if (!result[currentSection]) result[currentSection] = {};
      continue;
    }

    const kvMatch = trimmed.match(/^(\w+):\s+(.+)$/);
    if (kvMatch) {
      const key = kvMatch[1];
      let value: string | number = kvMatch[2];
      if (!isNaN(Number(value)) && value !== '') value = Number(value);

      if (currentSection && currentSubSection) {
        const section = result[currentSection] as Record<string, unknown>;
        const sub = (section[currentSubSection] as Record<string, unknown>) || {};
        sub[key] = value;
        section[currentSubSection] = sub;
      } else if (currentSection) {
        const section = result[currentSection] as Record<string, unknown>;
        if (typeof value === 'string' && !isNaN(Number(value)) && value !== '') {
          section[key] = Number(value);
        } else {
          section[key] = value;
        }
      } else {
        result[key] = value;
      }
      continue;
    }

    const subSectionMatch = trimmed.match(/^  (\w+):\s*$/);
    if (subSectionMatch && currentSection) {
      currentSubSection = subSectionMatch[1];
      const section = result[currentSection] as Record<string, unknown>;
      if (!section[currentSubSection]) section[currentSubSection] = {};
    }
  }

  return result;
}

function mergeHermesYaml(
  existing: Record<string, unknown>,
  profile: Profile | TargetProfile
): string {
  const model = (existing.model as Record<string, unknown>) || {};
  model.provider = profile.providerType;
  model.default = profile.defaultModel;
  model.base_url = profile.baseUrl;
  existing.model = model;

  const providers = (existing.providers as Record<string, unknown>) || {};
  const providerConfig = (providers[profile.providerType] as Record<string, unknown>) || {};
  providerConfig.base_url = profile.baseUrl;
  providerConfig.api_key = profile.apiKey;
  providers[profile.providerType] = providerConfig;
  existing.providers = providers;

  const aliases = (existing.model_aliases as Record<string, unknown>) || {};
  aliases.fast = profile.fastModel;
  aliases.reasoning = profile.reasoningModel;
  existing.model_aliases = aliases;

  let output = '# Generated by Agent Env Switcher\n\n';

  if (existing.model) {
    output += 'model:\n';
    const m = existing.model as Record<string, unknown>;
    for (const [k, v] of Object.entries(m)) {
      output += `  ${k}: ${v}\n`;
    }
    output += '\n';
  }

  if (existing.providers) {
    output += 'providers:\n';
    const p = existing.providers as Record<string, unknown>;
    for (const [provName, provConfig] of Object.entries(p)) {
      output += `  ${provName}:\n`;
      const pc = provConfig as Record<string, unknown>;
      for (const [k, v] of Object.entries(pc)) {
        output += `    ${k}: ${v}\n`;
      }
    }
    output += '\n';
  }

  if (existing.model_aliases) {
    output += 'model_aliases:\n';
    const a = existing.model_aliases as Record<string, unknown>;
    for (const [k, v] of Object.entries(a)) {
      output += `  ${k}: ${v}\n`;
    }
  }

  return output;
}

function formatCodexToml(profile: Profile | TargetProfile): string {
  return `# Generated by Agent Env Switcher
# DO NOT edit manually while using profile management

[model]
provider = "${profile.providerType}"
model = "${profile.defaultModel}"
fast_model = "${profile.fastModel}"
reasoning_model = "${profile.reasoningModel}"

[provider]
base_url = "${profile.baseUrl}"
api_key = "${profile.apiKey}"
`;
}

function parseCodexToml(content: string): Record<string, Record<string, string>> {
  const result: Record<string, Record<string, string>> = {};
  let currentSection = '';

  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const sectionMatch = trimmed.match(/^\[(\w+)\]$/);
    if (sectionMatch) {
      currentSection = sectionMatch[1];
      result[currentSection] = {};
      continue;
    }

    if (currentSection) {
      const kvMatch = trimmed.match(/^(\w+)\s*=\s*"?(.+?)"?\s*$/);
      if (kvMatch) {
        result[currentSection][kvMatch[1]] = kvMatch[2];
      }
    }
  }

  return result;
}

function mergeCodexToml(
  existing: Record<string, Record<string, string>>,
  profile: Profile | TargetProfile
): string {
  const modelSection = existing['model'] || {};
  modelSection.provider = profile.providerType;
  modelSection.model = profile.defaultModel;
  modelSection.fast_model = profile.fastModel;
  modelSection.reasoning_model = profile.reasoningModel;
  existing['model'] = modelSection;

  const providerSection = existing['provider'] || {};
  providerSection.base_url = profile.baseUrl;
  providerSection.api_key = profile.apiKey;
  existing['provider'] = providerSection;

  let output = '# Generated by Agent Env Switcher\n\n';

  for (const [section, values] of Object.entries(existing)) {
    output += `[${section}]\n`;
    for (const [k, v] of Object.entries(values)) {
      output += `${k} = "${v}"\n`;
    }
    output += '\n';
  }

  return output;
}

